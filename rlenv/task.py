COMPOSE = """# Generated by rlenv/task.py: Inspect sandbox for the {starter} starter.
services:
  default:
    image: {image}
    init: true
    command: tail -f /dev/null
    working_dir: /workspace
    network_mode: none
    cpus: {cpus}
    mem_limit: 8g
"""


def prepare(experiments, cpus, rebuild=False):
    """Generate the starter, build the images and write the sandbox compose
    file. Returns (starter name, compose file)."""
    starter, tag = ensure_images(experiments, rebuild)
    path = HERE / "docker/generated" / f"compose.{starter}.yaml"
    path.parent.mkdir(exist_ok=True)
    path.write_text(COMPOSE.format(starter=starter, image=tag, cpus=cpus))
    return starter, path


# ------------------------------------------------------------------ submission
async def read_submission(state):
    """losses.py, REPORT.md (empty if missing) and the diff against the starter."""
    sb = sandbox()
    async def read(name):
        try:
            return await sb.read_file(f"{WORKSPACE}/{name}")
        except Exception:
            return ""
    losses, report = await read("losses.py"), await read("REPORT.md")
    original = (HERE / "starter" / state.metadata["starter"] / "losses.py").read_text()
    diff = "".join(difflib.unified_diff(original.splitlines(True), losses.splitlines(True),
                                        "a/losses.py", "b/losses.py"))
    return losses, report, diff


async def run_grader(losses, args, timeout):
    """Run a grader script on the submitted losses.py in the grader image."""
    with tempfile.TemporaryDirectory() as tmp:
        Path(tmp, "losses.py").write_text(losses)
        os.chmod(tmp, 0o755)
        proc = await asyncio.create_subprocess_exec(
            *grader_command(tmp, args), stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
        try:
            out, err = await asyncio.wait_for(proc.communicate(), timeout)
        except asyncio.TimeoutError:
            proc.kill()
            return {"passed": False, "error": f"grader timed out after {timeout}s"}
    return parse_grader_output(out, err)


# ------------------------------------------------------------------ scorers
@scorer(metrics=[mean()])
def theory():
    async def score(state: TaskState, target: Target):
        losses, _, _ = await read_submission(state)
        if not losses:
            return Score(value=0, explanation="no losses.py")
        result = await run_grader(losses, THEORY_ARGS, 1800)
        explanation = (f"passed={result.get('passed')} passed_topk={result.get('passed_topk')} "
                       f"passed_with_tis={result.get('passed_with_tis')}")
        return Score(value=int(bool(result.get("passed"))), explanation=explanation, metadata=result)
    return score


@scorer(metrics=[mean()])
def guard():
    async def score(state: TaskState, target: Target):
        losses, report, _ = await read_submission(state)
        if not losses:
            return Score(value=0, explanation="no losses.py")
        config = configuration(report)
        result = await run_grader(losses, [*GUARD_ARGS, *config], 3600)
        result["configuration"] = config
        return Score(value=int(bool(result.get("passed"))), explanation=json.dumps(result)[:4000], metadata=result)
    return score


def parse_verdict(text):
    text = text.strip()
    fenced = re.search(r"```(?:json)?\s*(\{.*\})\s*```", text, re.S)
    if fenced:
        text = fenced.group(1)
    start, end = text.find("{"), text.rfind("}")
    return json.loads(text[start:end + 1])


@scorer(metrics={"score": [mean()], "rediscovered": [mean()], "discovered": [mean()]})
def judge(models):
    async def score(state: TaskState, target: Target):
        losses, report, diff = await read_submission(state)
        prompt = judge_lib.build_prompt(state.metadata["prompt"], report or "(no REPORT.md)", diff or "(no change)")
        verdicts, errors = [], []
        for name in models:
            try:
                out = await get_model(name).generate(prompt)
                verdict = parse_verdict(out.completion)
                judge_lib.score(verdict)  # validates
                verdicts.append(verdict)
            except Exception as e:
                errors.append(f"{name}: {type(e).__name__}: {e}"[:300])
        if not verdicts:
            return Score(value={"score": 0, "rediscovered": 0, "discovered": 0},
                         explanation="no valid judge verdict: " + "; ".join(errors))
        agg = judge_lib.aggregate(verdicts)
        return Score(value={"score": agg["score"], "rediscovered": int(agg["rediscovered"]),
                            "discovered": int(agg["discovered"])},
                     explanation=json.dumps({k: v for k, v in agg.items() if k != "judges"}),
                     metadata={"aggregate": agg, "verdicts": verdicts, "errors": errors})
    return score


# ------------------------------------------------------------------ task
@task
def score_centering(levels="L2a,L2b,L3,L4", experiments=True, judges="", hours=2.0, tokens=5_000_000,
                    messages=500, compaction=True, cpus=4, epochs=1, rebuild=False):
    """One run per level (times epochs). A run ends when the agent calls
    submit() or hits a limit:
      hours     working time (time spent waiting on the model API not counted);
                wall-clock time is capped at 3x that as a safety net
      tokens    total tokens over the run (input + output), the cost bound
      messages  total messages, a guard against loops
    compaction: summarize or compact the history near the context limit
    (native compaction when the provider has it, else a summary).
    experiments: whether the agent can run training (run_dev.sh, dev/mini.py);
    the starter and the tools section of the prompt follow it."""
    levels = [l.strip() for l in str(levels).split(",") if l.strip()]
    judges = [j.strip() for j in str(judges).split(",") if j.strip()]
    flag = lambda v: str(v).lower() not in ("false", "0", "no")
    experiments = flag(experiments)
    starter, compose_file = prepare(experiments, cpus, rebuild=bool(rebuild))
    budget = CPU_BUDGET.format(cpus=cpus, hours=float(hours))
    samples = []
    for level in levels:
        text = prompts.compose(level, budget, experiments=experiments)
        samples.append(Sample(id=f"{starter}-{level}", input=text,
                              metadata={"level": level, "starter": starter, "experiments": experiments,
                                        "prompt": text},
                              sandbox=("docker", str(compose_file))))
    scorers = [theory(), guard()] + ([judge(judges)] if judges else [])
    agent = react(
        prompt=("You are a machine learning researcher. Work in /workspace with the tools you have. "
                "When losses.py and REPORT.md are final, call submit() with a one-line summary."),
        tools=[bash(timeout=3600), python(timeout=3600), text_editor()],
        compaction=CompactionAuto() if flag(compaction) else None,
    )
    seconds = int(float(hours) * 3600)
    return Task(dataset=MemoryDataset(samples), solver=agent, scorer=scorers, epochs=int(epochs),
                working_limit=seconds, time_limit=3 * seconds,
                token_limit=int(tokens) if tokens else None,
                message_limit=int(messages) if messages else None)
